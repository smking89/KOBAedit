"""Companion plugin generation for exported maps.

A mapa exported by the studio is plain ``WorldSerialization``; anything that has
to happen at runtime (branding messages, loot hints, map signature checks) needs
a server plugin. This module renders that plugin for either framework:

* **Oxide** - ``RustPlugin`` subclass, dropped into ``oxide/plugins``.
* **Carbon** - ``CarbonPlugin`` subclass, dropped into ``carbon/plugins``.

The generated source is deliberately dependency-free: no third-party plugins, no
CUI, nothing that breaks when the game patches. Dropping the file in is all a
server owner has to do.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

DEFAULT_AUTHOR = "KOBA Studios"
DEFAULT_VERSION = "1.0.0"
FRAMEWORKS = ("oxide", "carbon")


@dataclass(slots=True)
class PluginSpec:
    """Everything the emitted plugin needs baked into its source."""

    plugin_name: str
    class_name: str
    project_name: str
    map_size: int = 4000
    loot_tier: int = 2
    seed: int = 0
    author: str = DEFAULT_AUTHOR
    version: str = DEFAULT_VERSION
    welcome_message: str = ""
    generated_at: str = ""

    def to_dict(self) -> dict[str, Any]:
        return {
            "pluginName": self.plugin_name,
            "className": self.class_name,
            "projectName": self.project_name,
            "mapSize": self.map_size,
            "lootTier": self.loot_tier,
            "seed": self.seed,
            "author": self.author,
            "version": self.version,
            "welcomeMessage": self.welcome_message,
            "generatedAt": self.generated_at,
        }


def _pascal(value: str) -> str:
    words = re.findall(r"[A-Za-z0-9]+", value)
    if not words:
        return "Map"
    return "".join(word[:1].upper() + word[1:] for word in words)


def _csharp_string(value: str) -> str:
    return value.replace("\\", "\\\\").replace('"', '\\"').replace("\r", " ").replace("\n", " ")


def _number(value: Any, default: float) -> float:
    try:
        return float(value)
    except (TypeError, ValueError):
        return default


def build_spec(
    draft: dict[str, Any],
    *,
    author: str = DEFAULT_AUTHOR,
    version: str = DEFAULT_VERSION,
) -> PluginSpec:
    """Derive a ``PluginSpec`` from a wizard draft (camelCase, as saved by the UI)."""

    if not isinstance(draft, dict):
        raise TypeError("draft must be an object")

    project_name = str(draft.get("name") or "Untitled Map").strip() or "Untitled Map"
    terrain = draft.get("terrain") or {}
    loot = draft.get("loot") or {}
    branding = draft.get("branding") or {}

    size = int(_number(terrain.get("sizeMetres", terrain.get("size_metres")), 4000))
    tier = int(_number(loot.get("tier"), 2))
    seed = int(_number(terrain.get("seed"), 0))
    class_stem = _pascal(project_name)

    welcome = str(branding.get("welcomeMessage") or "").strip()
    if not welcome:
        welcome = f"Welcome to {project_name}."

    return PluginSpec(
        plugin_name=f"KOBA {project_name}",
        class_name=f"Koba{class_stem}",
        project_name=project_name,
        map_size=max(0, size),
        loot_tier=min(3, max(1, tier)),
        seed=seed,
        author=author,
        version=version,
        welcome_message=welcome,
        generated_at=datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
    )


_OXIDE_TEMPLATE = """// KOBA Studios companion plugin for the map "{project}".
// Generated by KOBA Studios on {generated}. Re-export from the studio instead of
// editing this file: the studio overwrites it on every export.
//
// Install: copy into `oxide/plugins/` and let Oxide compile it.

namespace Koba.Generated
{{
    [Info("{plugin}", "{author}", "{version}")]
    [Description("Companion plugin for the KOBA map {project}.")]
    public class {klass} : RustPlugin
    {{
        private const string ProjectName = "{project}";
        private const int MapSizeMetres = {size};
        private const int LootTier = {tier};
        private const int MapSeed = {seed};
        private const string WelcomeMessage = "{welcome}";

        protected override void LoadDefaultConfig()
        {{
            Config["ProjectName"] = ProjectName;
            Config["MapSizeMetres"] = MapSizeMetres;
            Config["LootTier"] = LootTier;
            Config["WelcomeMessage"] = WelcomeMessage;
            SaveConfig();
        }}

        private void OnServerInitialized()
        {{
            Puts($"{{ProjectName}} ({{MapSizeMetres}} m, seed {{MapSeed}}, loot tier {{LootTier}}) is live.");
        }}

        private void OnPlayerConnected(BasePlayer player)
        {{
            if (player == null || string.IsNullOrEmpty(WelcomeMessage))
            {{
                return;
            }}

            player.ChatMessage(WelcomeMessage);
        }}
    }}
}}
"""

_CARBON_TEMPLATE = """// KOBA Studios companion plugin for the map "{project}".
// Generated by KOBA Studios on {generated}. Re-export from the studio instead of
// editing this file: the studio overwrites it on every export.
//
// Install: copy into `carbon/plugins/` and let Carbon compile it.

using Carbon.Plugins;

namespace Koba.Generated
{{
    [Info("{plugin}", "{author}", "{version}")]
    public class {klass} : CarbonPlugin
    {{
        private const string ProjectName = "{project}";
        private const int MapSizeMetres = {size};
        private const int LootTier = {tier};
        private const int MapSeed = {seed};
        private const string WelcomeMessage = "{welcome}";

        protected override void OnServerInitialized(bool initial)
        {{
            Puts($"{{ProjectName}} ({{MapSizeMetres}} m, seed {{MapSeed}}, loot tier {{LootTier}}) is live.");
        }}

        private void OnPlayerConnected(BasePlayer player)
        {{
            if (player == null || string.IsNullOrEmpty(WelcomeMessage))
            {{
                return;
            }}

            player.ChatMessage(WelcomeMessage);
        }}
    }}
}}
"""


def render_plugin(spec: PluginSpec, framework: str = "oxide") -> str:
    """Render the plugin source for ``framework`` (``oxide`` or ``carbon``)."""

    if framework not in FRAMEWORKS:
        raise ValueError(f"unknown framework '{framework}', expected one of {FRAMEWORKS}")

    template = _OXIDE_TEMPLATE if framework == "oxide" else _CARBON_TEMPLATE
    generated = spec.generated_at or datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    return template.format(
        project=_csharp_string(spec.project_name),
        plugin=_csharp_string(spec.plugin_name),
        author=_csharp_string(spec.author),
        version=_csharp_string(spec.version),
        klass=spec.class_name,
        size=spec.map_size,
        tier=spec.loot_tier,
        seed=spec.seed,
        welcome=_csharp_string(spec.welcome_message),
        generated=generated,
    )


def write_plugin(
    draft: dict[str, Any],
    target_dir: str | Path,
    *,
    framework: str = "oxide",
    spec: PluginSpec | None = None,
) -> Path:
    """Write the companion plugin next to an exported map and return its path."""

    spec = spec or build_spec(draft)
    directory = Path(target_dir)
    directory.mkdir(parents=True, exist_ok=True)
    target = directory / f"{spec.class_name}.cs"
    target.write_text(render_plugin(spec, framework), encoding="utf-8")
    return target
